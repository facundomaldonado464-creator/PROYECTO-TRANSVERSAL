private materiaData obtenerDatos() {
    return new materiaData();
}

private int obtenerId() {
    try {
        int id = Integer.parseInt(txtId.getText().trim());

        if (id <= 0) {
            throw new NumberFormatException();
        }

        return id;

    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException(
            "Ingresá un ID de materia válido."
        );
    }
}

private Materia leerMateria(boolean necesitaId) {
    int id = -1;

    if (necesitaId) {
        id = obtenerId();
    }

    String nombre = txtNombre.getText().trim();
    String textoAnio = txtFecha.getText().trim();

    if (nombre.isEmpty()) {
        throw new IllegalArgumentException(
            "Ingresá el nombre de la materia."
        );
    }

    int anio;

    try {
        anio = Integer.parseInt(textoAnio);

        if (anio < 1900 || anio > 2100) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException(
            "El año debe ser un número entre 1900 y 2100."
        );
    }

    return new Materia(
        id,
        nombre,
        anio,
        chkActivo.isSelected()
    );
}

private void limpiarCampos() {
    txtId.setText("");
    txtNombre.setText("");
    txtFecha.setText("");
    chkActivo.setSelected(false);
}

private void cargarTabla() {
    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"ID Materia", "Nombre", "Año", "Activo"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    try {
        List<Materia> lista = obtenerDatos().listarTodas();

        for (Materia materia : lista) {
            modelo.addRow(new Object[]{
                materia.getIdMateria(),
                materia.getNombre(),
                materia.getAnio(),
                materia.isActivo() ? "Sí" : "No"
            });
        }

        jTable1.setModel(modelo);

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
            this,
            "Error al cargar las materias: " + ex.getMessage()
        );
    }
}



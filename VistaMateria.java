    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        
try {
    Materia materia = leerMateria(true);
    materiaData datos = obtenerDatos();

    if (datos.buscar(materia.getIdMateria()) == null) {
        JOptionPane.showMessageDialog(
            this, "No existe una materia con ese ID."
        );
        return;
    }

    datos.actualizar(materia);

    JOptionPane.showMessageDialog(
        this, "Materia actualizada correctamente."
    );

    limpiarCampos();
    cargarTabla();

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this, ex.getMessage());

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(
        this, "Error al actualizar: " + ex.getMessage()
    );
}

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
try {
    int id = obtenerId();

    int respuesta = JOptionPane.showConfirmDialog(
        this,
        "¿Seguro que querés eliminar la materia con ID " + id + "?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
    );

    if (respuesta != JOptionPane.YES_OPTION) {
        return;
    }

    materiaData datos = obtenerDatos();

    if (datos.buscar(id) == null) {
        JOptionPane.showMessageDialog(
            this, "No existe una materia con ese ID."
        );
        return;
    }

    datos.borrar(id);

    JOptionPane.showMessageDialog(
        this, "Materia eliminada correctamente."
    );

    limpiarCampos();
    cargarTabla();

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this, ex.getMessage());

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(
        this, "Error al eliminar: " + ex.getMessage()
    );
}

    }//GEN-LAST:event_btnEliminarActionPerformed


private AlumnoData obtenerDatos() {
    return new AlumnoData(new persistencia.miConexion());
}

private int obtenerId() {
    try {
        int id = Integer.parseInt(txtId.getText().trim());

        if (id <= 0) {
            throw new NumberFormatException();
        }

        return id;

    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException(
            "Ingresá un ID de alumno válido."
        );
    }
}

private Alumno leerAlumno(boolean necesitaId) {
    int id = -1;

    if (necesitaId) {
        id = obtenerId();
    }

    String nombre = txtNombre.getText().trim();
    String textoDni = txtDni.getText().trim();

    if (nombre.isEmpty()) {
        throw new IllegalArgumentException(
            "Ingresá el nombre del alumno."
        );
    }

    int dni;

    try {
        dni = Integer.parseInt(textoDni);

        if (dni <= 0) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException(
            "El DNI debe ser un número entero positivo."
        );
    }

    LocalDate fecha = convertirFecha(
        txtFecNac.getText().trim()
    );

    return new Alumno(
        id,
        dni,
        nombre,
        fecha,
        chkActivo.isSelected()
    );
}

private LocalDate convertirFecha(String texto) {
    DateTimeFormatter formato =
        new DateTimeFormatterBuilder()
            .appendPattern("dd/MM/")
            .appendValueReduced(
                ChronoField.YEAR, 2, 2, 1930
            )
            .toFormatter()
            .withResolverStyle(ResolverStyle.STRICT);

    try {
        return LocalDate.parse(texto, formato);

    } catch (DateTimeParseException ex) {
        throw new IllegalArgumentException(
            "La fecha debe ser válida y tener formato dd/MM/aa.\n"
            + "Ejemplo: 25/08/05"
        );
    }
}

private void limpiarCampos() {
    txtId.setText("");
    txtNombre.setText("");
    txtDni.setText("");
    txtFecNac.setText("");
    chkActivo.setSelected(false);
}


